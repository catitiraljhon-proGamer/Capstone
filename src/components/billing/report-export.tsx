/** Who made an export: the signed-in staff member, shown as "Generated By" in Excel and the printable report. */
export type ReportAuthor = { name: string; role: string };

export function useReportAuthor(): ReportAuthor {
  const { user } = useSessionUser();
  // Reports are a Billing Clerk page, so that is the role until the session loads.
  return { name: user?.name ?? "—", role: roleLabels[user?.role ?? "billing-clerk"] };
}

