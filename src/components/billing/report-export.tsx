/** Export Selected (n): a menu to download Excel or open the printable report. */
export function ExportMenu({ count, disabled = false, onExcel, onPdf }: { count: number; disabled?: boolean; onExcel: () => void; onPdf: () => void }) {
  const [menuOpen, setMenuOpen] = useState(false);
  /** Opens the menu toward the right when the button sits near the left edge, as it does once a header wraps on phones. */
  const [alignLeft, setAlignLeft] = useState(false);
  const menuRef = useRef<HTMLDivElement>(null);
  const buttonRef = useRef<HTMLButtonElement>(null);
  const enabled = count > 0 && !disabled;
  const isOpen = menuOpen && enabled;

  // The menu closes on a click outside it or on Escape.
  useEffect(() => {
    if (!isOpen) return;
    const closeOnOutsideClick = (event: MouseEvent) => {
      if (!menuRef.current?.contains(event.target as Node)) setMenuOpen(false);
    };
    const closeOnEscape = (event: KeyboardEvent) => {
      if (event.key === "Escape") setMenuOpen(false);
    };
    document.addEventListener("mousedown", closeOnOutsideClick);
    document.addEventListener("keydown", closeOnEscape);
    return () => {
      document.removeEventListener("mousedown", closeOnOutsideClick);
      document.removeEventListener("keydown", closeOnEscape);
    };
  }, [isOpen]);

  const toggleMenu = () => {
    const button = buttonRef.current?.getBoundingClientRect();
    // The menu is 18rem wide; aligned to the button's right edge it would run past the left of the screen.
    setAlignLeft(Boolean(button && button.right < 18 * 16 + 16));
    setMenuOpen((open) => !open);
  };
  const choose = (action: () => void) => {
    setMenuOpen(false);
    action();
  };
  const formats = [
    { label: "Excel (.xlsx)", hint: "A spreadsheet with a summary sheet and the selected rows", icon: FileSpreadsheet, action: onExcel },
    { label: "PDF (printable)", hint: "A printable report to save as PDF or print", icon: Printer, action: onPdf },
  ];

  return (
    <div ref={menuRef} className="relative">
      <Button ref={buttonRef} variant="outline" disabled={!enabled} onClick={toggleMenu} aria-haspopup="menu" aria-expanded={isOpen}>
        <Download className="mr-2 h-4 w-4" />
        {count ? `Export Selected (${count})` : "Select Rows to Export"}
        {count ? <ChevronDown className="ml-2 h-4 w-4" aria-hidden="true" /> : null}
      </Button>
      {isOpen ? (
        <div role="menu" aria-label="Export format" className={`absolute ${alignLeft ? "left-0" : "right-0"} z-20 mt-2 w-72 max-w-[calc(100vw-2rem)] rounded-xl border border-stone-200 bg-white p-1.5 shadow-lg`}>
          {formats.map(({ label, hint, icon: Icon, action }) => (
            <button
              key={label}
              type="button"
              role="menuitem"
              onClick={() => choose(action)}
              className="flex w-full items-start gap-3 rounded-lg px-3 py-2.5 text-left transition hover:bg-rose-50 focus:bg-rose-50 focus:outline-none"
            >
              <span className="grid h-8 w-8 shrink-0 place-items-center rounded-lg bg-rose-50 text-red-700"><Icon className="h-4 w-4" aria-hidden="true" /></span>
              <span className="min-w-0">
                <span className="block text-sm font-semibold text-stone-950">{label}</span>
                <span className="block text-xs text-stone-500">{hint}</span>
              </span>
            </button>
          ))}
        </div>
      ) : null}
    </div>
  );
}

