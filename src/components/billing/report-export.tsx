/**
 * A report on top of the page with the letterhead, its details, and Prepared by / Checked by lines.
 * Print / Save PDF opens the browser's print window, where the clerk saves it as a PDF or prints it.
 */
export function PrintableReport({ title, generated, author, details, onClose, children }: {
  title: string;
  generated: string;
  author: ReportAuthor;
  /** The filters and scope shown under Generated and Generated by. */
  details: [string, string][];
  onClose: () => void;
  children: ReactNode;
}) {
  const contact = useContactDetails(true) ?? defaultContactDetails;
  useModalBehavior(true, onClose);
  const preparedBy = `${author.name}, ${author.role}`;
  const rows: [string, string][] = [["Generated", generated], ["Generated by", preparedBy], ...details];

  return createPortal(
    <div role="dialog" aria-modal="true" aria-label={`Printable ${title}`} className="report-print fixed inset-0 z-50 overflow-y-auto bg-stone-100 px-4 py-6 sm:px-8">
      <style>{printStyles}</style>
      <div className="print-toolbar mx-auto mb-4 flex max-w-5xl flex-wrap items-center justify-between gap-3">
        <p className="text-sm text-stone-600">Print / Save PDF opens the print window. Choose Save as PDF or a printer there.</p>
        <div className="flex flex-wrap gap-2">
          <Button variant="outline" onClick={onClose}><X className="mr-2 h-4 w-4" />Close</Button>
          <Button onClick={() => window.print()}><Printer className="mr-2 h-4 w-4" />Print / Save PDF</Button>
        </div>
      </div>

      <article className="print-sheet mx-auto max-w-5xl rounded-xl border border-stone-200 bg-white p-6 text-sm text-stone-950 shadow-sm sm:p-10">
        <header>
          <Image src="/G4/image.png" alt="G4 Builders Inc" width={1726} height={500} className="h-auto w-40 object-contain" />
          <p className="mt-3 text-xl font-semibold tracking-tight">G4 Builders Inc</p>
          <p className="mt-1 text-xs text-stone-600">{contact.address}</p>
          <p className="text-xs text-stone-600">{contact.phone} | {contact.email}</p>
          <h1 className="mt-6 text-2xl font-semibold tracking-tight text-red-700 print:mt-4">{title}</h1>
        </header>

        <dl className="mt-4 grid gap-x-8 gap-y-3 border-t-2 border-red-700 pt-4 sm:grid-cols-2">
          {rows.map(([label, value]) => (
            <div key={label} className="min-w-0">
              <dt className="text-xs font-semibold uppercase tracking-wide text-stone-500">{label}</dt>
              <dd className="mt-0.5 break-words">{value || "—"}</dd>
            </div>
          ))}
        </dl>

        {children}

        {/* Tighter on paper, so a short report keeps its signature lines on the same page. */}
        <div className="report-section mt-12 grid gap-10 text-xs text-stone-600 sm:grid-cols-2 print:mt-6">
          <p className="border-t border-stone-400 pt-2">Prepared by: {preparedBy}</p>
          <p className="border-t border-stone-400 pt-2">Checked by:</p>
        </div>
      </article>
    </div>,
    document.body,
  );
}

/** `nowrap` keeps reference numbers and dates on one line instead of breaking at the hyphen or comma. */
export type PrintColumn<Row> = { header: string; value: (row: Row) => string; numeric?: boolean; nowrap?: boolean };

/** The Excel columns as printable text: pesos with centavos and readable dates. `nowrap` lists the reference columns. */
export function printColumnsFrom<Row>(columns: XlsxColumn<Row>[], nowrap: string[] = []): PrintColumn<Row>[] {
  return columns.map((column) => ({
    header: column.header,
    numeric: column.format === "peso",
    nowrap: column.format === "date" || nowrap.includes(column.header),
    value: (row) => {
      const value = column.value(row);
      if (column.format === "peso" && typeof value === "number") return formatPeso(value);
      if (column.format === "date" && typeof value === "string" && /^\d{4}-\d{2}-\d{2}$/.test(value)) return billingDate(value);
      return String(value);
    },
  }));
}

export function ReportTable<Row extends { id: string }>({ title, columns, rows, total }: { title: string; columns: PrintColumn<Row>[]; rows: Row[]; total?: string[] }) {
  const align = (column: PrintColumn<Row>) =>
    `${column.numeric ? "text-right tabular-nums whitespace-nowrap" : "text-left"} ${column.nowrap ? "whitespace-nowrap" : ""}`;
  return (
    <section className="report-section mt-8 print:mt-6">
      <h2 className="text-base font-semibold tracking-tight">{title}</h2>
      {rows.length === 0 ? (
        <p className="mt-2 text-stone-500">None in this selection.</p>
      ) : (
        <div className="mt-2 overflow-x-auto">
          <table className="w-full min-w-[40rem] border-collapse text-xs">
            <thead className="bg-red-700 text-white">
              <tr>{columns.map((column) => <th key={column.header} scope="col" className={`px-2 py-2 font-semibold ${align(column)}`}>{column.header}</th>)}</tr>
            </thead>
            <tbody>
              {rows.map((row) => (
                <tr key={row.id} className="border-b border-stone-200 align-top">
                  {columns.map((column) => <td key={column.header} className={`px-2 py-2 ${align(column)}`}>{column.value(row)}</td>)}
                </tr>
              ))}
              {total ? (
                <tr className="border-t-2 border-stone-400 font-semibold">
                  {columns.map((column, index) => <td key={column.header} className={`px-2 py-2 ${align(column)}`}>{total[index] ?? ""}</td>)}
                </tr>
              ) : null}
            </tbody>
          </table>
        </div>
      )}
    </section>
  );
}
